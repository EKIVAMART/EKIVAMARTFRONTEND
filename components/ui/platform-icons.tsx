export type PlatformIconProps = IconProps & { absoluteStrokeWidth?: boolean };
export type LucideIcon = React.FC<PlatformIconProps>;
function themed(IconComponent: Icon): LucideIcon {
  return function PlatformIcon({ weight, fill, className, strokeWidth: _strokeWidth, absoluteStrokeWidth: _absoluteStrokeWidth, ...props }: PlatformIconProps) {
    // Lucide stroke widths do not apply to Phosphor's filled SVG paths.
    void _strokeWidth;
    void _absoluteStrokeWidth;
    const selected = (fill != null && fill !== 'none' && fill !== 'transparent') || /(?:^|\s)fill-(?!none|transparent)/.test(className ?? '');
    return <IconComponent {...props} className={className} weight={weight ?? (selected ? 'fill' : 'duotone')} />;
  };
}
